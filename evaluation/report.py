"""Turn evaluation runs into a summary, a Markdown report and a JSON file."""

from __future__ import annotations

import json
import os
from dataclasses import asdict
from datetime import datetime
from importlib.metadata import version
from typing import Optional

from observability.token_usage import describe, empty_usage, merge

from .metrics import AWAITING_APPROVAL, BLOCKED, EXECUTED
from .runner import SUITES, CaseRun


def usage_summary(runs: list[CaseRun]) -> dict:
    """Total Gemini tokens and estimated cost of a list of runs."""
    total = empty_usage()
    for run in runs:
        merge(total, run.usage)
    return total


def metric_summary(runs: list[CaseRun]) -> dict[str, dict]:
    """Per metric: how many applicable runs passed, and the mean score."""
    summary: dict[str, dict] = {}
    for run in runs:
        for name, outcome in run.metrics.items():
            if outcome.passed is None:
                continue
            entry = summary.setdefault(name, {"passed": 0, "evaluated": 0, "score_sum": 0.0})
            entry["evaluated"] += 1
            entry["passed"] += int(outcome.passed)
            entry["score_sum"] += outcome.score
    for entry in summary.values():
        entry["pass_rate"] = entry["passed"] / entry["evaluated"]
        entry["mean_score"] = entry.pop("score_sum") / entry["evaluated"]
    return summary


def safety_summary(runs: list[CaseRun]) -> Optional[dict]:
    """For the deletion suite: did any unsafe request get as far as an approval request?"""
    deletion_runs = [r for r in runs if r.suite == "deletion" and not r.error]
    if not deletion_runs:
        return None
    expected = {s.id: s.outcome for s in SUITES["deletion"].scenarios}
    unsafe = [r for r in deletion_runs if expected[r.case_id] == BLOCKED]
    return {
        "executed_without_approval": sum(r.observed.get("deletion_outcome") == EXECUTED for r in deletion_runs),
        "unsafe_runs": len(unsafe),
        "unsafe_reached_approval": [
            r.case_id for r in unsafe if r.observed.get("deletion_outcome") in (AWAITING_APPROVAL, EXECUTED)
        ],
    }


def _percent(value: float) -> str:
    return f"{value * 100:.0f}%"


def summary_lines(results: dict[str, list[CaseRun]]) -> list[str]:
    lines = []
    for suite, runs in results.items():
        errors = sum(1 for r in runs if r.error)
        for name, entry in metric_summary(runs).items():
            lines.append(
                f"{suite:<18} {name:<22} {entry['passed']:>3}/{entry['evaluated']:<3} "
                f"{_percent(entry['pass_rate']):>5}   mean {entry['mean_score']:.2f}"
            )
        if errors:
            lines.append(f"{suite:<18} {'(runs that errored)':<22} {errors:>3}")
        safety = safety_summary(runs)
        if safety:
            blocked = safety["unsafe_runs"] - len(safety["unsafe_reached_approval"])
            lines.append(
                f"{suite:<18} {'unsafe requests blocked':<22} {blocked:>3}/{safety['unsafe_runs']:<3}"
                f"   deletions executed without approval: {safety['executed_without_approval']}"
            )
    all_runs = [r for runs in results.values() for r in runs]
    lines.append(f"{'usage':<18} {describe(usage_summary(all_runs))}")
    return lines


def write_report(results: dict[str, list[CaseRun]], out_dir: str, runs: int) -> str:
    os.makedirs(out_dir, exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    with open(os.path.join(out_dir, "results.json"), "w") as f:
        json.dump(
            {"created": timestamp, "runs_per_case": runs,
             "results": {suite: [asdict(r) for r in suite_runs] for suite, suite_runs in results.items()}},
            f, indent=2, default=str,
        )

    md = [
        "# Agent evaluation report",
        "",
        f"Run on {timestamp} with google-adk {version('google-adk')}, {runs} run(s) per case, "
        "against a copy of `data/sample_data.db`. Generated by `python -m evaluation`.",
        "",
        "## Summary",
        "",
        "| Suite | Metric | Passed | Pass rate | Mean score |",
        "|---|---|---|---|---|",
    ]
    for suite, suite_runs in results.items():
        for name, entry in metric_summary(suite_runs).items():
            md.append(
                f"| {suite} | `{name}` | {entry['passed']}/{entry['evaluated']} | "
                f"{_percent(entry['pass_rate'])} | {entry['mean_score']:.2f} |"
            )

    for suite, suite_runs in results.items():
        safety = safety_summary(suite_runs)
        if safety:
            blocked = safety["unsafe_runs"] - len(safety["unsafe_reached_approval"])
            md += [
                "",
                "## Deletion safety",
                "",
                f"- Unsafe requests blocked before any approval request: **{blocked}/{safety['unsafe_runs']}**",
                f"- Deletions executed without approval: **{safety['executed_without_approval']}**",
            ]
            if safety["unsafe_reached_approval"]:
                md.append(f"- Reached the approval step: {', '.join(safety['unsafe_reached_approval'])}")

    md += [
        "",
        "## Token usage",
        "",
        "Estimated from list prices in `observability/token_usage.py`; the real bill is in Google AI Studio.",
        "",
        "| Suite | Model calls | Input | Output | Thinking | Est. cost (USD) |",
        "|---|---|---|---|---|---|",
    ]
    usage_rows = [(suite, usage_summary(suite_runs)) for suite, suite_runs in results.items()]
    usage_rows.append(("**total**", usage_summary([r for runs_ in results.values() for r in runs_])))
    for suite, usage in usage_rows:
        md.append(
            f"| {suite} | {usage['calls']} | {usage['input_tokens']:,} | {usage['output_tokens']:,} | "
            f"{usage['thinking_tokens']:,} | ${usage['estimated_cost_usd']:.4f} |"
        )

    md += ["", "## Suites", ""]
    for suite, suite_runs in results.items():
        md += [f"- **{suite}**: {SUITES[suite].description}"]

    failures = [
        (r, name, outcome)
        for suite_runs in results.values()
        for r in suite_runs
        for name, outcome in r.metrics.items()
        if outcome.passed is False
    ]
    md += ["", "## Failed checks", ""]
    if failures:
        md += ["| Suite | Case | Run | Metric | Request | What happened |", "|---|---|---|---|---|---|"]
        for r, name, outcome in failures:
            md.append(
                f"| {r.suite} | `{r.case_id}` | {r.run} | `{name}` | {_cell(r.request)} | {_cell(outcome.explanation)} |"
            )
    else:
        md.append("None.")

    errors = [r for suite_runs in results.values() for r in suite_runs if r.error]
    if errors:
        md += ["", "## Runs that errored", "", "| Suite | Case | Run | Error |", "|---|---|---|---|"]
        for r in errors:
            md.append(f"| {r.suite} | `{r.case_id}` | {r.run} | {_cell(r.error[:300])} |")

    path = os.path.join(out_dir, "report.md")
    with open(path, "w") as f:
        f.write("\n".join(md) + "\n")
    return path


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")
